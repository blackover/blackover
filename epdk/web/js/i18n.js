let current = 'tr';

export function setLanguage(lang) {
  current = DICT[lang] ? lang : 'tr';
  document.documentElement.lang = current;
  applyStatic();
  return current;
}

export function getLanguage() {
  return current;
}

/** Çeviri anahtarını çözer. */
export function t(key, fallback = '') {
  return DICT[current][key] ?? DICT.tr[key] ?? fallback ?? key;
}

/** Sunucudan gelen `{label_tr, label_en}` çiftinden doğru dili seçer. */
export function pick(object, base) {
  if (!object) return '';
  return object[`${base}_${current}`] || object[`${base}_tr`] || '';
}

/** data-i18n taşıyan sabit DOM öğelerini günceller. */
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((node) => {
    node.textContent = t(node.dataset.i18n, node.textContent);
  });
}
